class PrismModel:
    """延迟构建 torch 模块，保证 --self-check 在无 torch 环境下可跑。"""

    def __init__(self, vocab_size: int, preset: Dict[str, Any], dropout: float = 0.0,
                 seed: int = 0) -> None:
        import torch
        import torch.nn as nn
        import torch.nn.functional as F

        torch.manual_seed(seed)
        dim = preset["dim"]
        n_layers, n_heads = preset["n_layers"], preset["n_heads"]
        head_dim = dim // n_heads
        if dim % n_heads:
            raise ValueError(f"dim={dim} 不能被 n_heads={n_heads} 整除")
        hidden_ffn = max(int(round(dim * preset["ffn_mult"] * 2 / 3 / 64)) * 64, 64)

        class RMSNorm(nn.Module):
            def __init__(self, d: int, eps: float = 1e-6):
                super().__init__()
                self.weight = nn.Parameter(torch.ones(d))
                self.eps = eps

            def forward(self, x):
                # fp32 累加 + 缩放，再转回激活 dtype（AMP 下权重不降精度）
                h = x.float()
                out = h * torch.rsqrt(h.pow(2).mean(-1, keepdim=True) + self.eps)
                return (out * self.weight).to(x.dtype)

        def rope(t: int, start: int = 0):
            inv = 1.0 / (10000.0 ** (torch.arange(0, head_dim, 2, device=rope.dev).float() / head_dim))
            pos = torch.arange(start, start + t, device=rope.dev).float()
            f = torch.outer(pos, inv)
            return f.cos(), f.sin()

        rope.dev = None  # type: ignore[attr-defined]

        def apply_rope(x, cos, sin):
            cos, sin = cos.to(x.dtype), sin.to(x.dtype)
            x1, x2 = x[..., : x.shape[-1] // 2], x[..., x.shape[-1] // 2:]
            rot = torch.cat((-x2, x1), dim=-1)
            return x * torch.cat((cos, cos), dim=-1) + rot * torch.cat((sin, sin), dim=-1)

        def sdpa(q, k, v, is_causal: bool, attn_mask=None):
            if hasattr(F, "scaled_dot_product_attention"):
                kwargs = {"dropout_p": 0.0, "is_causal": is_causal, "attn_mask": attn_mask}
                if attn_mask is not None:
                    kwargs["is_causal"] = False
                return F.scaled_dot_product_attention(q, k, v, **kwargs)
            scores = q @ k.transpose(-2, -1) / math.sqrt(q.size(-1))
            if attn_mask is not None:
                scores = scores.masked_fill(~attn_mask, float("-inf"))
            elif is_causal:
                m = torch.ones(q.size(-2), k.size(-2), dtype=torch.bool, device=q.device).tril()
                scores = scores.masked_fill(~m, float("-inf"))
            return torch.softmax(scores.float(), -1).to(q.dtype) @ v

        class Attention(nn.Module):
            def __init__(self):
                super().__init__()
                self.qkv = nn.Linear(dim, 3 * dim, bias=False)
                self.proj = nn.Linear(dim, dim, bias=False)
                self.qn, self.kn = RMSNorm(head_dim), RMSNorm(head_dim)
                self.drop = nn.Dropout(dropout)

            def step(self, x, cos, sin, past):
                b, t, _ = x.shape
                q, k, v = self.qkv(x).split(dim, dim=2)
                q = q.view(b, t, n_heads, head_dim).transpose(1, 2)
                k = k.view(b, t, n_heads, head_dim).transpose(1, 2)
                v = v.view(b, t, n_heads, head_dim).transpose(1, 2)
                q, k = self.qn(q), self.kn(k)          # QK-Norm
                q, k = apply_rope(q, cos, sin), apply_rope(k, cos, sin)
                if past is None:
                    nk, nv = k, v
                    o = sdpa(q, k, v, True)
                else:
                    pk, pv = past
                    nk, nv = torch.cat([pk, k], 2), torch.cat([pv, v], 2)
                    if t == 1:
                        o = sdpa(q, nk, nv, False)
                    else:
                        mask = torch.ones(t, nk.size(2), dtype=torch.bool, device=x.device).tril(
                            diagonal=pk.size(2))
                        o = sdpa(q, nk, nv, False, mask)
                o = o.transpose(1, 2).contiguous().view(b, t, dim)
                return self.drop(self.proj(o)), (nk, nv)

        class Block(nn.Module):
            def __init__(self):
                super().__init__()
                self.n1, self.n2 = RMSNorm(dim), RMSNorm(dim)
                self.attn = Attention()
                self.w1 = nn.Linear(dim, hidden_ffn, bias=False)
                self.w3 = nn.Linear(dim, hidden_ffn, bias=False)
                self.w2 = nn.Linear(hidden_ffn, dim, bias=False)
                self.drop = nn.Dropout(dropout)

            def step(self, x, cos, sin, past):
                a, kv = self.attn.step(self.n1(x), cos, sin, past)
                x = x + a
                n = self.n2(x)
                return x + self.drop(self.w2(F.silu(self.w1(n)) * self.w3(n))), kv

        class Model(nn.Module):
            def __init__(self):
                super().__init__()
                self.embed = nn.Embedding(vocab_size, dim)
                self.blocks = nn.ModuleList([Block() for _ in range(n_layers)])
                self.nf = RMSNorm(dim)
                self.head = nn.Linear(dim, vocab_size, bias=False)
                self.head.weight = self.embed.weight        # tied embedding
                for m in self.modules():
                    if isinstance(m, nn.Linear):
                        nn.init.normal_(m.weight, 0.0, 0.02)
                nn.init.normal_(self.embed.weight, 0.0, 0.02)
                self.cfg = dict(vocab_size=vocab_size, **preset, dropout=dropout)

            def body(self, ids, past=None):
                b, t = ids.shape
                cache = past[0][0].size(2) if past else 0
                if t + cache > preset["max_seq"]:
                    raise ValueError(f"序列 {t + cache} 超过 max_seq={preset['max_seq']}")
                rope.dev = ids.device
                cos, sin = rope(t, cache)
                x = self.embed(ids)
                kv = []
                for i, blk in enumerate(self.blocks):
                    x, k = blk.step(x, cos, sin, past[i] if past else None)
                    kv.append(k)
                return self.nf(x), kv

            def forward(self, ids, targets=None, weights=None, return_hidden=False):
                h, _ = self.body(ids)
                logits = self.head(h)
                loss = None
                if targets is not None:
                    ce = torch.nn.functional.cross_entropy(
                        logits.reshape(-1, vocab_size).float(), targets.reshape(-1),
                        reduction="none").view_as(targets)
                    if weights is not None:
                        loss = (ce * weights).sum() / weights.sum().clamp(min=1.0)
                    else:
                        loss = ce.mean()
                return logits, loss, (h if return_hidden else None)

            def incremental(self, ids, past=None):
                h, kv = self.body(ids, past)
                return self.head(h), kv

            def n_params(self, non_embedding=False):
                n = sum(p.numel() for p in self.parameters())
                return n - self.embed.weight.numel() if non_embedding else n

        self.torch = torch
        self.net = Model()
        self.dim = dim
        self.head_dim = head_dim
        print(f"[model] preset={preset} params={self.net.n_params():,} "
              f"(non-embedding {self.net.n_params(True):,}) vocab={vocab_size}")


def to_device(batch: Dict[str, Any], torch, device, vocab: Vocab):
    x = torch.tensor(batch["x"], dtype=torch.long, device=device)
    y = torch.tensor(batch["y"], dtype=torch.long, device=device)
    w = torch.tensor(batch["w"], dtype=torch.float32, device=device)
    return x, y, w


def grad_norms(model: PrismModel, vocab: Vocab) -> Dict[str, float]:
    """按 token 类型分组的嵌入梯度范数（方案 §8.6 要求，骨架里缺的这一条）。"""
    g = model.net.embed.weight.grad
    if g is None:
        return {}
    return {
        "grad_norm_all": round(float(g.norm()), 5),
        "grad_norm_text_rows": round(float(g[:vocab.ctrl_start].norm()), 5),
        "grad_norm_control_rows": round(float(g[vocab.ctrl_start:vocab.ctrl_end].norm()), 5),
    }


def grad_norm_summary(history: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """方案 §8.6：按 token 类型监控梯度范数，给出控制/文本行比值摘要。"""
    pairs = [(r.get("grad_norm_control_rows"), r.get("grad_norm_text_rows"))
             for r in history if r.get("grad_norm_control_rows") and r.get("grad_norm_text_rows")]
    ratios = [c / t for c, t in pairs if t and t > 0]
    if not ratios:
        return {"status": "no_data"}
    ratios.sort()
    return {"n_steps": len(ratios),
            "control_over_text_ratio_mean": round(sum(ratios) / len(ratios), 4),
            "control_over_text_ratio_max": round(ratios[-1], 4),
            "control_over_text_ratio_p50": round(ratios[len(ratios) // 2], 4),
            "note": "§8.6：若决策 token 梯度持续显著高于代码 token，说明损失权重失衡"}


def embedding_geometry(model: PrismModel, vocab: Vocab, seqs: Sequence[Sequence[int]],
                       torch) -> Dict[str, Any]:
    """方案 §7 阶段一检查点：决策 token 嵌入是否与代码 token 落入同一可分空间。

    同时报告「从未在任何训练序列里出现过的决策 token」个数——v2 全库 19 个
    决策 token 里只有 3 个 ``<D:EDIT=*>`` 被训练过，其余 16 个是死权重。
    """
    net = model.net
    with torch.no_grad():
        e = net.embed.weight.detach().float().cpu()
    seen_dec = {i for s in seqs for i in s if i in vocab.decision_ids}
    dec_ids = sorted(vocab.decision_ids)
    text_ids = list(range(min(vocab.ctrl_start, 512)))  # 抽样，避免 O(vocab^2)
    e_dec = e[dec_ids]
    e_text = e[text_ids]
    e_dec_n = e_dec / e_dec.norm(dim=1, keepdim=True).clamp(min=1e-8)
    e_text_n = e_text / e_text.norm(dim=1, keepdim=True).clamp(min=1e-8)
    sim = e_dec_n @ e_text_n.T                      # (n_dec, n_text)
    vals = sim.flatten().tolist()
    vals.sort()

    def pct(q):
        return round(vals[min(len(vals) - 1, int(q * len(vals)))], 4)

    return {
        "n_decision_tokens": len(dec_ids),
        "n_decision_tokens_seen_in_train": len(seen_dec),
        "n_decision_tokens_never_trained": len(dec_ids) - len(seen_dec),
        "never_trained_token_examples": [vocab.text_of(i) for i in dec_ids
                                          if i not in seen_dec][:8],
        "cosine_dec_vs_text": {"min": round(vals[0], 4), "p25": pct(0.25),
                               "p50": pct(0.50), "p75": pct(0.75),
                               "max": round(vals[-1], 4),
                               "mean": round(sum(vals) / len(vals), 4)},
        "n_text_rows_sampled": len(text_ids),
        "note": "§7 检查点：只看随机初始化/训练后的嵌入余弦分布；接近 0 且从未训练的决策 token 多，"
                "说明阶段一「词表共存」前提未成立",
    }


def train_group(model: PrismModel, batches_by_epoch, val_batches, vocab: Vocab,
                device, cfg, autocast, scaler, torch, tag: str,
                out_dir: Path, kind_table) -> Dict[str, Any]:
    """训练一个组，val loss 最优即存 checkpoint，返回训练摘要。"""
    net = model.net
    try:
        opt = torch.optim.AdamW(net.parameters(), lr=cfg["lr"],
                                weight_decay=cfg["weight_decay"], betas=(0.9, 0.95),
                                fused=(device.type == "cuda"))
    except TypeError:  # 老版本无 fused
        opt = torch.optim.AdamW(net.parameters(), lr=cfg["lr"],
                                weight_decay=cfg["weight_decay"], betas=(0.9, 0.95))
    total_batches = sum(len(b) for b in batches_by_epoch)
    warmup = max(1, int(total_batches * cfg["warmup_ratio"]))
    history: List[Dict[str, Any]] = []
    best = {"val_loss": float("inf"), "epoch": -1}
    t0 = time.time()
    step = 0
    log_fh = (out_dir / "train_log.jsonl").open("a", encoding="utf-8")

    def evaluate_val() -> float:
        net.eval()
        tot, n = 0.0, 0
        with torch.no_grad():
            for b in val_batches:
                x, y, w = to_device(b, torch, device, vocab)
                with autocast():
                    _, loss, _ = net(x, y, w)
                tot += float(loss)
                n += 1
        net.train()
        return tot / max(n, 1)

    try:
        net.train()
        for epoch, batches in enumerate(batches_by_epoch):
            for bi, b in enumerate(batches):
                lr = cfg["lr"] * (step + 1) / warmup if step < warmup else \
                    cfg["lr"] * (cfg["min_lr_ratio"] + (1 - cfg["min_lr_ratio"]) * 0.5 *
                                 (1 + math.cos(math.pi * (step - warmup) /
                                               max(total_batches - warmup, 1))))
                for g in opt.param_groups:
                    g["lr"] = lr
                x, y, w = to_device(b, torch, device, vocab)
                with autocast():
                    logits, loss, _ = net(x, y, w)
                if scaler is not None:
                    scaler.scale(loss).backward()
                    scaler.unscale_(opt)
                else:
                    loss.backward()
                norms = grad_norms(model, vocab)
                torch.nn.utils.clip_grad_norm_(net.parameters(), cfg["grad_clip"])
                if scaler is not None:
                    scaler.step(opt)
                    scaler.update()
                else:
                    opt.step()
                opt.zero_grad(set_to_none=True)
                kinds = kind_table[y]
                with torch.no_grad():
                    pred = logits.argmax(-1)
                    keep = w > 0
                    accs = {}
                    for name, kid in vocab.KIND.items():
                        m = keep & (kinds == kid)
                        if int(m.sum()) > 0:
                            accs[name + "_acc"] = round(float((pred[m] == y[m]).float().mean()), 4)
                step += 1
                if step % cfg["log_every"] == 0 or step == 1:
                    rec = {"group": tag, "epoch": epoch, "step": step,
                           "loss": round(float(loss.detach()), 5), "lr": round(lr, 8),
                           "elapsed_s": round(time.time() - t0, 1), **norms, **accs}
                    history.append(rec)
                    log_fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    log_fh.flush()
                    print(f"[{tag}] ep{epoch} step {step}/{total_batches} "
                          f"loss={rec['loss']:.4f} decision_acc={accs.get('decision_acc', '-')}")
            vl = evaluate_val()
            if vl < best["val_loss"]:
                best = {"val_loss": vl, "epoch": epoch}
                torch.save({"model": net.state_dict(), "config": net.cfg,
                            "epoch": epoch, "tag": tag, "val_loss": vl},
                           out_dir / "checkpoints" / f"{tag}_best.pt")
            if cfg.get("epoch_limit") and epoch + 1 >= cfg["epoch_limit"]:
                break
    finally:
        log_fh.close()
    return {"tag": tag, "steps": step, "best_val_loss": round(best["val_loss"], 5),
            "best_epoch": best["epoch"], "elapsed_s": round(time.time() - t0, 1),
            "final_train_loss": history[-1]["loss"] if history else None,
            "history": history}


