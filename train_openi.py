def allowed_next(history: Sequence[int], vocab: Vocab) -> Optional[List[int]]:
    """结构状态机（与 src/lightprism/tokenizer.py::allowed_next 同口径）。"""
    st = vocab.structure
    in_task = in_code = False
    last: Optional[int] = None
    used_points = set()
    for i in history:
        if i == st["<TASK>"]:
            in_task, last = True, i
        elif i == st["</TASK>"]:
            in_task, last = False, i
        elif i == st["<CODE>"]:
            in_code, last = True, i
        elif i == st["</CODE>"]:
            in_code, last = False, i
        elif i in vocab.decision_ids:
            last = i
            t = vocab.text_of(i)
            used_points.add(DECISION_RE.fullmatch(t).group(1))  # type: ignore[union-attr]
        elif i in vocab.validation_ids:
            last, used_points = i, set()
    v_ids = sorted(vocab.validation_ids)
    if in_task:
        return [st["</TASK>"]]
    if in_code:
        return [st["</CODE>"]]
    if last is None or last == st["<TASK>"]:
        return [st["</TASK>"]] if last == st["<TASK>"] else [st["<TASK>"]]
    if last == st["</CODE>"]:
        return v_ids
    if last == st["<CODE>"]:
        return [st["</CODE>"]]
    free = [i for p, ids in vocab.point_token_ids.items() if p not in used_points for i in ids]
    return sorted(free + [st["<CODE>"]])


def check_structure(gen_ids: Sequence[int], vocab: Vocab, expect_validation: bool) -> Tuple[bool, List[str]]:
    """无外部状态机、只看模型自己吐出的 id 序列做结构复核。"""
    st = vocab.structure
    problems: List[str] = []
    code_open = code_close = 0
    seen_points = set()
    in_code = False
    last_ctrl = None
    for tid in gen_ids:
        if tid == st["<TASK>"] or tid == st["</TASK>"]:
            problems.append("生成段里出现 TASK 标记")
        elif tid == st["<CODE>"]:
            code_open += 1
            in_code = True
        elif tid == st["</CODE>"]:
            code_close += 1
            in_code = False
        elif tid in vocab.decision_ids:
            if in_code:
                problems.append("决策 token 出现在 CODE 段内（命名空间被污染）")
            p = DECISION_RE.fullmatch(vocab.text_of(tid)).group(1)  # type: ignore[union-attr]
            if p in seen_points:
                problems.append(f"决策点 {p} 同一步重复选择")
            seen_points.add(p)
        elif tid in vocab.validation_ids:
            if in_code:
                problems.append("验证 token 出现在 CODE 段内")
            if last_ctrl != st["</CODE>"]:
                problems.append("验证 token 没有紧跟 </CODE>")
        if tid in vocab.control_ids:
            last_ctrl = tid
    if code_open != 1 or code_close != 1:
        problems.append(f"CODE 标记数不对 open={code_open} close={code_close}")
    if in_code:
        problems.append("CODE 段未闭合")
    if expect_validation:
        if not gen_ids or gen_ids[-1] not in vocab.validation_ids:
            problems.append("结尾不是 <V:...>")
    elif not gen_ids or gen_ids[-1] != st["</CODE>"]:
        problems.append("结尾不是 </CODE>")
    return (not problems), problems


def generate(model: PrismModel, vocab: Vocab, sample: Dict[str, Any], device,
             torch, autocast, max_new: int, constrained: bool,
             expect_validation: bool) -> Dict[str, Any]:
    net = model.net
    net.eval()
    st = vocab.structure
    prompt = [st["<TASK>"]] + vocab.encode_text(sample["task"]) + [st["</TASK>"]]
    ids = list(prompt)
    generated: List[int] = []
    past = None
    t0 = time.time()
    with torch.no_grad():
        window = torch.tensor([ids], dtype=torch.long, device=device)
        with autocast():
            logits, past = net.incremental(window)
        last = logits[0, -1, :]
        for _ in range(max_new):
            logits = last.clone()
            if constrained:
                allow = allowed_next(ids, vocab)
                if allow is not None:
                    s = set(allow)
                    blocked = [i for i in vocab.control_ids if i not in s]
                    if blocked:
                        logits[torch.tensor(blocked, dtype=torch.long, device=device)] = float("-inf")
            nxt = int(torch.argmax(logits).item())
            ids.append(nxt)
            generated.append(nxt)
            stop = (nxt in vocab.validation_ids) if expect_validation else (nxt == st["</CODE>"])
            if stop or len(ids) >= net.cfg["max_seq"]:
                break
            with autocast():
                lg, past = net.incremental(
                    torch.tensor([[nxt]], dtype=torch.long, device=device), past)
            last = lg[0, -1, :]
    elapsed = max(time.time() - t0, 1e-6)
    ok, problems = check_structure(generated, vocab, expect_validation)
    truncated = len(generated) >= max_new
    # 抽出 CODE 段文本
    code_ids: List[int] = []
    inside = False
    for i in generated:
        if i == st["<CODE>"]:
            inside = True
            continue
        if i == st["</CODE>"]:
            break
        if inside:
            code_ids.append(i)
    code_text = vocab.decode_text(code_ids).strip()
    ans = _answer_json(str(sample["steps"][0]["code"]))
    gen_json = _answer_json(code_text)
    j_valid = gen_json is not None
    j_exact = j_valid and ans is not None and gen_json == ans
    return {
        "structure_ok": ok, "structure_problems": problems, "truncated": truncated,
        "counts_toward_structure_rate": ok and not truncated,
        "code_text": code_text, "answer_text": str(sample["steps"][0]["code"]),
        "json_valid": j_valid, "json_exact": j_exact,
        "is_json_task": sample["_format"] == "json",
        "n_decision": sum(1 for i in generated if i in vocab.decision_ids),
        "n_tokens": len(generated),
        "tokens_per_s": round(len(generated) / elapsed, 1),
        "ids": generated,
    }


def collect_hidden(model: PrismModel, vocab: Vocab, rows: Sequence[Dict[str, Any]],
                   seqs: Sequence[Sequence[int]], device, torch, autocast):
    """冻结主干，收集决策 token 的探针特征。

    **必须取决策 token 的前一个位置（pos-1）作为预测特征。** v1 取的是 pos
    自身那一行：Transformer 的 residual stream 起点就是 ``embed(ids[pos])``，
    位置 pos 的 hidden 里已经含决策 token 自己的 embedding，线性探针等于
    「照抄输入里的答案」，与模型有没有学到决策毫无关系。实测 v1 在
    C 组 / 打乱组探针宏平均都恰好 1.000，连随机初始化的模型都能做到 ——
    这是标签泄漏，不是能力。

    这里同时收 pos 自身位置作为**泄漏对照**写进报告：它应当接近 1.0，
    而主探针（pos-1）必须明显更低，两者之差才可解释为「模型在预测」。
    """
    net = model.net
    net.eval()
    data: List[Tuple[str, int, Any, Any]] = []
    prev_dist: Dict[str, int] = defaultdict(int)
    with torch.no_grad():
        for row, ids in zip(rows, seqs):
            seq = list(ids)[:net.cfg["max_seq"]]
            if len(seq) < 2:
                continue
            x = torch.tensor([seq], dtype=torch.long, device=device)
            with autocast():
                _, _, h = net(x, return_hidden=True)
            h = h[0].float().cpu()
            for pos, tid in enumerate(seq):
                if pos == 0 or tid not in vocab.decision_ids:
                    continue
                m = DECISION_RE.fullmatch(vocab.text_of(tid))
                p, o = m.group(1), m.group(2)  # type: ignore[union-attr]
                if o not in vocab.point_option_id.get(p, {}):
                    continue
                prev_dist[describe_prev(seq, pos, vocab)] += 1
                data.append((p, vocab.point_option_id[p][o], h[pos - 1], h[pos]))
    collect_hidden.prev_dist = dict(prev_dist)  # type: ignore[attr-defined]
    return data


def describe_prev(seq: Sequence[int], pos: int, vocab: Vocab) -> str:
    """决策 token 前一位置的可读描述，用于报告「特征是否退化为常数」。"""
    prev = seq[pos - 1]
    if prev in vocab.control_ids:
        return vocab.text_of(prev)
    return "<text>"


def train_probe(model: PrismModel, vocab: Vocab, splits, split_seqs, device,
                torch, autocast, epochs: int, seed: int) -> Dict[str, Any]:
    """线性探针：主特征 = 决策 token 前一位置 hidden；另跑一份「自身位置」泄漏对照。

    只在有独立 test 样本的点上报宏平均；每个点单独一个线性头。
    """
    tr = collect_hidden(model, vocab, splits["train"], split_seqs["train"], device, torch, autocast)
    te = collect_hidden(model, vocab, splits["test"], split_seqs["test"], device, torch, autocast)
    torch.manual_seed(seed)

    def fit(feature_idx: int) -> Dict[str, Any]:
        by_tr: Dict[str, List] = defaultdict(list)
        by_te: Dict[str, List] = defaultdict(list)
        for p, y, h_pre, h_self in tr:
            by_tr[p].append((y, (h_pre, h_self)[feature_idx]))
        for p, y, h_pre, h_self in te:
            by_te[p].append((y, (h_pre, h_self)[feature_idx]))
        per_point: Dict[str, Any] = {}
        accs: List[float] = []
        for p in vocab.points:
            n_cls = len(vocab.point_options[p])
            a, b = by_tr.get(p, []), by_te.get(p, [])
            if not a and not b:
                per_point[p] = {"status": "no_samples", "n_classes": n_cls,
                                "random_baseline": round(1 / n_cls, 4)}
                continue
            if not b:
                per_point[p] = {"status": "no_test_samples", "n_train": len(a), "n_test": 0,
                                "n_classes": n_cls, "random_baseline": round(1 / n_cls, 4)}
                continue
            head = torch.nn.Linear(model.dim, n_cls).to(device)
            X = torch.stack([h for _, h in a])
            Y = torch.tensor([y for y, _ in a], dtype=torch.long, device=device)
            opt = torch.optim.AdamW(head.parameters(), lr=1e-3)
            for _ in range(epochs):
                opt.zero_grad()
                loss = torch.nn.functional.cross_entropy(head(X.to(device)), Y)
                loss.backward()
                opt.step()
            Xt = torch.stack([h for _, h in b]).to(device)
            Yt = torch.tensor([y for y, _ in b], dtype=torch.long, device=device)
            with torch.no_grad():
                acc = float((head(Xt).argmax(-1) == Yt).float().mean())
            per_point[p] = {"status": "ok", "n_train": len(a), "n_test": len(b),
                            "accuracy": round(acc, 4), "n_classes": n_cls,
                            "random_baseline": round(1 / n_cls, 4), "eval_split": "heldout_test"}
            accs.append(acc)
        return {"per_point": per_point,
                "macro_accuracy": round(sum(accs) / len(accs), 4) if accs else None,
                "points_with_test": sorted(p for p, v in per_point.items()
                                           if v.get("status") == "ok")}

    main = fit(0)       # pos-1：不含标签本身，是真正的预测特征
    leak = fit(1)       # pos：标签写在输入里，用作泄漏对照
    covered = main["points_with_test"]
    # v3：显式报告「决策 token 前一位置」分布。若 100% 是同一个控制 token，
    # 说明 pos-1 特征退化成常数，判据 ① 测不到「决策前的上下文状态」。
    prev_dist = getattr(collect_hidden, "prev_dist", {}) or {}
    const_feature = len(prev_dist) == 1 and sum(prev_dist.values()) > 0
    return {
        **main,
        "feature_position": "pos-1（决策 token 前一位置，不含标签本身）",
        "feature_prev_token_distribution": prev_dist,
        "feature_is_constant": const_feature,
        "self_position_control": {
            "feature_position": "pos（决策 token 自身位置，标签写在输入里的泄漏对照）",
            "macro_accuracy": leak["macro_accuracy"],
            "per_point": {p: v.get("accuracy") for p, v in leak["per_point"].items()},
        },
        "params": sum(model.dim * len(vocab.point_options[p]) + len(vocab.point_options[p])
                      for p in covered),
        "n_train_rows": len(tr), "n_test_rows": len(te),
    }


def train_probe_rival(model: PrismModel, vocab: Vocab, splits, split_seqs, device,
                      torch, autocast, epochs: int, seed: int) -> Dict[str, Any]:
    """A' 组：冻结主干 + **与探针完全相同的 pos-1 特征** + 非线性 MLP 头。

    v2 拿 579 参数的线性探针去比 390419 参数的 A 组文本分类器，参数量不对等。
    A' 与主探针同特征、同 train/test，只把线性头换成 MLP；若 A' 也明显更准，
    说明差距来自「特征不够 + 线性不可分」，而不是「共享表征没编码决策」。
    """
    tr = collect_hidden(model, vocab, splits["train"], split_seqs["train"], device, torch, autocast)
    te = collect_hidden(model, vocab, splits["test"], split_seqs["test"], device, torch, autocast)
    torch.manual_seed(seed + 31337)
    per_point: Dict[str, Any] = {}
    accs: List[float] = []
    for p in vocab.points:
        n_cls = len(vocab.point_options[p])
        a = [(y, h) for pt, y, h, _ in tr if pt == p]
        b = [(y, h) for pt, y, h, _ in te if pt == p]
        if not b:
            per_point[p] = {"status": "no_test_samples", "n_train": len(a), "n_test": 0,
                            "n_classes": n_cls}
            continue
        head = torch.nn.Sequential(
            torch.nn.Linear(model.dim, model.dim), torch.nn.ReLU(),
            torch.nn.Linear(model.dim, n_cls)).to(device)
        X = torch.stack([h for _, h in a]).to(device)
        Y = torch.tensor([y for y, _ in a], dtype=torch.long, device=device)
        opt = torch.optim.AdamW(head.parameters(), lr=1e-3)
        for _ in range(epochs):
            opt.zero_grad()
            loss = torch.nn.functional.cross_entropy(head(X), Y)
            loss.backward()
            opt.step()
        Xt = torch.stack([h for _, h in b]).to(device)
        Yt = torch.tensor([y for y, _ in b], dtype=torch.long, device=device)
        with torch.no_grad():
            acc = float((head(Xt).argmax(-1) == Yt).float().mean())
        per_point[p] = {"status": "ok", "n_train": len(a), "n_test": len(b),
                        "accuracy": round(acc, 4), "n_classes": n_cls,
                        "eval_split": "heldout_test"}
        accs.append(acc)
    return {"per_point": per_point,
            "macro_accuracy": round(sum(accs) / len(accs), 4) if accs else None,
            "points_with_test": sorted(p for p, v in per_point.items() if v.get("status") == "ok"),
            "params": sum(model.dim * model.dim + model.dim +
                          model.dim * len(vocab.point_options[p]) + len(vocab.point_options[p])
                          for p in per_point if per_point[p].get("status") == "ok"),
            "feature_position": "pos-1（与 C 组主探针完全同特征）",
            "note": "与 C 探针同特征、同切分，只把线性头换成 MLP；用于判断差距是否来自线性可分性"}


def train_decision_baseline(vocab: Vocab, splits, split_seqs, device, torch,
                            epochs: int, seed: int) -> Dict[str, Any]:
    """A 组：独立轻量决策模型（Embedding+MLP 多任务头），< 1M 参数。"""
    torch.manual_seed(seed)
    H = 128

    class Baseline(torch.nn.Module):
        def __init__(self):
            super().__init__()
            self.emb = torch.nn.Embedding(vocab.vocab_size, H, padding_idx=vocab.pad_id)
            self.fc = torch.nn.Sequential(torch.nn.Linear(H, H), torch.nn.ReLU())
            self.heads = torch.nn.ModuleDict({
                p: torch.nn.Linear(H, len(o)) for p, o in vocab.point_options.items()})

        def forward(self, ids):
            m = (ids != vocab.pad_id).float().unsqueeze(-1)
            h = (self.emb(ids) * m).sum(1) / m.sum(1).clamp(min=1.0)
            h = self.fc(h)
            return {p: head(h) for p, head in self.heads.items()}

    def rows_for(name):
        out = []
        for row, ids in zip(splits[name], split_seqs[name]):
            labels: Dict[str, int] = {}
            for tid in ids:
                if tid in vocab.decision_ids:
                    m = DECISION_RE.fullmatch(vocab.text_of(tid))
                    p, o = m.group(1), m.group(2)  # type: ignore[union-attr]
                    labels[p] = vocab.point_option_id[p][o]
            if labels:
                task = [vocab.structure["<TASK>"]] + vocab.encode_text(row["task"]) + [
                    vocab.structure["</TASK>"]]
                out.append((task, labels))
        return out

    tr, te = rows_for("train"), rows_for("test")
    net = Baseline().to(device)
    params = sum(p.numel() for p in net.parameters())
    opt = torch.optim.AdamW(net.parameters(), lr=3e-3)
    max_len = 256
    for _ in range(epochs):
        for task, labels in tr:
            ids = torch.tensor([task[:max_len]], dtype=torch.long, device=device)
            lg = net(ids)
            loss = sum(torch.nn.functional.cross_entropy(lg[p],
                       torch.tensor([y], dtype=torch.long, device=device))
                       for p, y in labels.items())
            opt.zero_grad()
            loss.backward()
            opt.step()
    per_point: Dict[str, Any] = {}
    accs: List[float] = []
    net.eval()
    for p in vocab.points:
        pts = [(task, y) for task, lab in te for p2, y in lab.items() if p2 == p]
        if not pts:
            per_point[p] = {"status": "no_samples", "random_baseline": round(1 / len(vocab.point_options[p]), 4)}
            continue
        hit = 0
        with torch.no_grad():
            for task, y in pts:
                ids = torch.tensor([task[:max_len]], dtype=torch.long, device=device)
                if int(net(ids)[p].argmax(-1).item()) == y:
                    hit += 1
        acc = hit / len(pts)
        per_point[p] = {"status": "ok", "n_test": len(pts), "accuracy": round(acc, 4),
                        "random_baseline": round(1 / len(vocab.point_options[p]), 4),
                        "eval_split": "heldout_test"}
        accs.append(acc)
    return {"per_point": per_point,
            "macro_accuracy": round(sum(accs) / len(accs), 4) if accs else None,
            "points_with_test": sorted(p for p, v in per_point.items() if v.get("status") == "ok"),
            "params": params, "n_train_rows": len(tr), "n_test_rows": len(te)}


