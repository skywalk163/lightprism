class Vocab:
    """2900 条实词表 + 控制 token 连续区间 + 训练用 PAD/UNK。

    分词用贪心最长匹配；L0 44 字强制一字一 token（词表构建时已保证
    多字 token 不含 L0 字，这里再兜一次，避免任何粘连）。
    """

    def __init__(self, v: Dict[str, Any]) -> None:
        self.tokens: List[str] = list(v["tokens"])
        lay = v["control_layout"]
        self.ctrl_start, self.ctrl_end = int(lay["start"]), int(lay["end"])
        self.structure: Dict[str, int] = {k: int(x) for k, x in lay["structure"].items()}
        self.decisions: Dict[str, int] = {k: int(x) for k, x in lay["decisions"].items()}
        self.validations: Dict[str, int] = {k: int(x) for k, x in lay["validations"].items()}
        self.index: Dict[str, int] = {t: i for i, t in enumerate(self.tokens)}
        self.pad_id = self.ctrl_end
        self.unk_id = self.ctrl_end + 1
        self.vocab_size = self.ctrl_end + 2

        kinds = v.get("kinds") or []
        self.l0_set = {t for t, k in zip(self.tokens, kinds) if k == "l0"}
        self.decision_ids = set(self.decisions.values())
        self.validation_ids = set(self.validations.values())
        self.structure_ids = set(self.structure.values())
        self.control_ids = list(range(self.ctrl_start, self.ctrl_end))

        self.point_options: Dict[str, List[str]] = defaultdict(list)
        self.point_token_ids: Dict[str, List[int]] = defaultdict(list)
        for text, tid in sorted(self.decisions.items(), key=lambda kv: kv[1]):
            m = DECISION_RE.fullmatch(text)
            if not m:
                raise ValueError(f"非法决策 token: {text}")
            self.point_options[m.group(1)].append(m.group(2))
            self.point_token_ids[m.group(1)].append(tid)
        self.points = sorted(self.point_options)
        self.point_option_id: Dict[str, Dict[str, int]] = {
            p: {o: i for i, o in enumerate(opts)} for p, opts in self.point_options.items()
        }
        self.unk_count = 0

        by_first: Dict[str, List[Tuple[str, int]]] = defaultdict(list)
        for i, t in enumerate(self.tokens[:self.ctrl_start]):
            if t and not t.startswith("<"):
                by_first[t[0]].append((t, i))
        for k in by_first:
            by_first[k].sort(key=lambda kv: -len(kv[0]))
        self.by_first = by_first

        # id -> 类型编号，供 torch 侧按 target 分组统计
        self.KIND = {"text": 0, "structure": 1, "decision": 2, "validation": 3,
                     "unk": 4, "pad": 5}
        self.kind_table: List[int] = [self.KIND["text"]] * self.vocab_size
        for i in self.structure_ids:
            self.kind_table[i] = self.KIND["structure"]
        for i in self.decision_ids:
            self.kind_table[i] = self.KIND["decision"]
        for i in self.validation_ids:
            self.kind_table[i] = self.KIND["validation"]
        self.kind_table[self.pad_id] = self.KIND["pad"]
        self.kind_table[self.unk_id] = self.KIND["unk"]

    def kind_of(self, tid: int) -> str:
        if tid == self.pad_id:
            return "pad"
        if tid == self.unk_id:
            return "unk"
        if tid in self.structure_ids:
            return "structure"
        if tid in self.decision_ids:
            return "decision"
        if tid in self.validation_ids:
            return "validation"
        return "text"

    def ctrl_id(self, text: str) -> int:
        for table in (self.structure, self.decisions, self.validations):
            if text in table:
                return table[text]
        raise ValueError(f"控制 token 不在词表里: {text}")

    def text_of(self, tid: int) -> str:
        for table in (self.structure, self.decisions, self.validations):
            for t, i in table.items():
                if i == tid:
                    return t
        raise ValueError(f"{tid} 不是控制 token")

    def encode_text(self, text: str) -> List[int]:
        for bad in ("<TASK>", "</TASK>", "<CODE>", "</CODE>", "<D:", "<V:"):
            if bad in text:
                raise ValueError(f"任务/代码文本里出现控制标记 {bad!r}，命名空间被污染")
        out: List[int] = []
        i, n = 0, len(text)
        while i < n:
            ch = text[i]
            if ch in self.l0_set:
                out.append(self.index.get(ch, self.unk_id))
                i += 1
                continue
            hit = None
            for tok, tid in self.by_first.get(ch, ()):
                if text.startswith(tok, i):
                    hit = (tok, tid)
                    break
            if hit:
                out.append(hit[1])
                i += len(hit[0])
            else:
                out.append(self.unk_id)
                self.unk_count += 1
                i += 1
        return out

    def decode_text(self, ids: Sequence[int]) -> str:
        out = []
        for i in ids:
            if i == self.pad_id:
                continue
            if i == self.unk_id:
                out.append("\ufffd")
            elif i < len(self.tokens):
                t = self.tokens[i]
                if not (t.startswith("<D:") or t.startswith("<V:") or t.startswith("<")):
                    out.append(t)
        return "".join(out)


def _answer_json(code: str) -> Optional[Any]:
    try:
        return json.loads(code)
    except Exception:
        return None


def rule_decisions(sample: Dict[str, Any], code: str) -> Dict[str, str]:
    """确定性规则派生的**合成**决策标签（仅机制验证，不是真实决策日志）。

    规则只用样本里可复核的字段（答案 JSON、代码长度、任务文本关键字），
    并在 report.md 里逐条列出，便于任何人重算。
    """
    ans = _answer_json(code)
    task = sample["task"]
    cat = str(sample.get("meta", {}).get("category", ""))
    n = len(code)
    d: Dict[str, str] = {}
    if isinstance(ans, dict) and cat == "decision" and ans.get("decision") in ("FR", "RW", "PATCH"):
        d["EDIT"] = str(ans["decision"])
    else:
        d["EDIT"] = "PATCH" if n < 120 else ("FR" if n < 320 else "RW")
    d["PLAN"] = "DECOMPOSE" if isinstance(ans, dict) and len(ans.get("subtasks") or []) >= 3 else "DIRECT"
    d["RETRY"] = "YES" if isinstance(ans, dict) and ans.get("ok") is False else "NO"
    if any(k in task for k in ("删除", "覆盖", "写入", "执行", "运行")):
        d["SAFE"] = "L2"
    elif any(k in task for k in ("文件", "目录", "源码")):
        d["SAFE"] = "L1"
    else:
        d["SAFE"] = "L0"
    diag = str(ans.get("code", "")) if isinstance(ans, dict) else ""
    d["FIX"] = "ADD_TYPE" if diag in ("L2002", "L2003") else (
        "RENAME" if diag in ("L4001", "L4002") else "REFACTOR")
    d["NEXT"] = "TEST" if str(sample.get("meta", {}).get("format")) == "code" else "EDIT"
    d["CTX"] = "FETCH" if len(task) > 120 else ("KEEP" if len(task) > 60 else "DROP")
    return d


def template_key(sample: Dict[str, Any]) -> str:
    """分组切分用的「模板簇」键：类别 + 抹掉可变部分后的 task 文本。

    v2 的 ``stratified_split`` 按 category 随机打散，同一模板的变体跨 train/test，
    decision 类 6 条 test 的 task 在 train 里一字不差出现过（A 组 1.000 是记忆
    不是泛化）。这里把数字/天干占位符归一化，保证同簇样本整体进同一 split。
    """
    s = _TEMPLATE_NUM_RE.sub("#", sample["task"])
    s = _TEMPLATE_VAR_RE.sub("@", s)
    s = re.sub(r"\s+", "", s)
    return f"{sample.get('_category', '')}|{s}"


def decision_window(sample: Dict[str, Any], vocab: Vocab) -> List[int]:
    """scattered 模式在 ``</TASK>`` 与决策 token 之间插入的任务文本窗口。

    **训练与推理必须用同一个窗口**：本函数是唯一真相，``build_ids()`` 与
    ``generate()`` 都调它。v3.1 只改训练侧、推理 prompt 仍止于 ``</TASK>``，
    导致分布不一致，判据 ③ 实测从 0.9808 崩到 0.4808。

    窗口由 ``sha256(task + code)`` 确定性派生，**不依赖调用顺序或 RNG 状态**，
    因此训练与推理两条路径即使在不同进程里也能算出同一窗口。
    """
    task_ids = vocab.encode_text(sample["task"])
    # 末尾 6 个 token 是各模板共有的固定套话（「…输出 JSON。」），排除掉
    # 以免 pos-1 又退化成同一个标点。太短的任务则退回整体。
    usable = task_ids[:-6] if len(task_ids) > 10 else task_ids
    if not usable:
        return []
    seed = hashlib.sha256(
        (sample["task"] + "\x00" + str(sample["steps"][0]["code"])).encode("utf-8")
    ).hexdigest()
    rng = random.Random(int(seed, 16))
    k = rng.randint(1, min(8, len(usable)))
    start = rng.randint(0, len(usable) - k)
    return usable[start:start + k]


def build_ids(sample: Dict[str, Any], vocab: Vocab, policy: str,
              shuffle_rng: Optional[random.Random] = None,
              decision_position: str = "fixed",
              position_rng: Optional[random.Random] = None) -> Tuple[List[int], Dict[str, str]]:
    """一条 Sample -> 统一自回归序列的 id 列表 + 该样本的决策标签。

    ``decision_position``：
    * ``fixed``（v2 行为）：决策 token 紧跟 ``</TASK>``。实测 50/50 条决策 token
      的前一位置都是 ``</TASK>``，pos-1 探针特征退化成常数，测不到「决策前的上下文状态」。
    * ``scattered``：在 ``</TASK>`` 与 ``<CODE>`` 之间插入一段**从任务文本随机位置
      截取**的 token 窗口，再放决策 token，使 pos-1 不再恒等于 ``</TASK>``。
      方案 §7「随机交错三类 token」。

      v3.1 修正：初版用 ``task_tail[-k:]`` 取末尾 k 个 token，但本库 363 条样本
      的 task 全以「输出 JSON。」结尾，实测 48/48 条决策 token 的前一 token
      都是同一个 ``。``(id=46) —— 只是把常数从 ``</TASK>`` 换成了 ``。``。
      改为随机起点截取窗口，并跳过尾部固定套话。
    """
    steps = sample["steps"]
    if not steps:
        raise ValueError("样本 steps 为空")
    code = str(steps[0]["code"])
    validation = str(steps[0].get("validation") or "PASS")
    vtext = f"<V:{validation}>"
    if vtext not in vocab.validations:
        raise ValueError(f"未登记的验证码 {vtext}")
    labels: Dict[str, str] = {}
    if policy == "real":
        cat = str(sample.get("meta", {}).get("category", ""))
        ans = _answer_json(code)
        if cat == "decision" and isinstance(ans, dict) and ans.get("decision") in ("FR", "RW", "PATCH"):
            labels["EDIT"] = str(ans["decision"])
    elif policy == "rule":
        labels = rule_decisions(sample, code)
        # 7 个点全注入会让决策密度 ~4.5%，突破方案 §8.5 的 2% 硬上限。
        # 按样本内容做确定性轮转，每条只保留 2 个点：密度 ~1.3%，
        # 且 7 个点在全集上都有正样本，探针不必只靠单点。
        pts = vocab.points
        h = int(hashlib.sha256((sample["task"] + code).encode("utf-8")).hexdigest(), 16)
        start = h % len(pts)
        keep = {pts[(start + j) % len(pts)] for j in range(2)}
        labels = {p: o for p, o in labels.items() if p in keep}
    elif policy == "off":
        labels = {}
    else:
        raise ValueError(f"未知决策策略 {policy}")

    if shuffle_rng is not None:
        shuffled = {}
        for p, opt in labels.items():
            opts = vocab.point_options.get(p, [])
            if len(opts) > 1:
                others = [o for o in opts if o != opt]
                shuffled[p] = shuffle_rng.choice(others)  # 强制换成别的选项
            else:
                shuffled[p] = opt
        labels = shuffled

    ids: List[int] = [vocab.structure["<TASK>"]]
    ids.extend(vocab.encode_text(sample["task"]))
    ids.append(vocab.structure["</TASK>"])
    if decision_position == "scattered" and labels:
        # 把任务文本中一段**随机位置**的 token 窗口挪到 </TASK> 之后，再放决策
        # token。这样 pos-1 既不恒为 </TASK>，也不恒为末尾那句固定套话「输出
        # JSON。」，探针才有机会测到「决策前的上下文状态」。
        #
        # v3.2 关键修正：`generate()` 必须用**同一个窗口**构造 prompt，
        # 否则训练序列在 </TASK> 后多了一段任务文本、推理 prompt 却没有，
        # 属于训练/推理分布不一致。实测它把判据 ③ 从 0.9808 打到 0.4808
        # （52 条里少 26 条合法）。窗口由 decision_window() 确定性产出，并挂到
        # 样本上，供 eval_generation 原样复用（无标签行不插窗口）。
        win = decision_window(sample, vocab)
        sample["_scatter_window"] = win
        ids.extend(win)
    elif decision_position not in ("fixed", "scattered"):
        raise ValueError(f"未知 --decision-position {decision_position}")
    for p in vocab.points:
        if p in labels:
            t = f"<D:{p}={labels[p]}>"
            if t not in vocab.decisions:
                raise ValueError(f"决策标签 {t} 不在封闭集合里")
            ids.append(vocab.decisions[t])
    ids.append(vocab.structure["<CODE>"])
    ids.extend(vocab.encode_text("\n" + code + "\n"))
    ids.append(vocab.structure["</CODE>"])
    ids.append(vocab.validations[vtext])
    return ids, labels


def strip_controls(ids: Sequence[int], vocab: Vocab) -> List[int]:
    """B 组消融：删掉决策 + 验证 token，只留任务/代码与 4 个结构标记。"""
    return [i for i in ids if i not in vocab.decision_ids and i not in vocab.validation_ids]


def load_samples(payload: Dict[str, Any]) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for key in ("json_tasks", "code_tasks", "err_tasks"):
        text = payload.get(key, "")
        if not text:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            if not line.strip():
                continue
            r = json.loads(line)
            if not r.get("task") or not r.get("steps"):
                raise ValueError(f"{key}:{lineno} 缺 task/steps")
            r["_source_file"] = key
            r["_category"] = str(r.get("meta", {}).get("category") or key)
            r["_format"] = str(r.get("meta", {}).get("format") or "code")
            rows.append(r)
    return rows


def stratified_split(rows: Sequence[Dict[str, Any]], seed: int,
                     group_split: bool = False,
                     coverage: Optional[Dict[str, Any]] = None) -> Dict[str, List[Dict[str, Any]]]:
    """按类别（或类别+模板簇）切 train/val/test。

    ``group_split=True`` 时同一 ``template_key`` 的变体整体进同一 split，
    避免 v2 里「decision 类 6 条 test 的 task 在 train 里一字不差出现」的泄漏。
    分组以 **cluster 为单位** 做 70/15/15，样本数会与 v2 的逐样本切分略有差异。
    """
    if group_split:
        by: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
        for r in rows:
            by[template_key(r)].append(r)
        clusters = list(by.values())
    else:
        by = defaultdict(list)
        for r in rows:
            by[r["_category"]].append(r)
        clusters = [[r] for r in sum(by.values(), [])]  # 每个样本自成一簇 = v2 行为

    rng = random.Random(seed)
    rng.shuffle(clusters)
    out: Dict[str, List[Dict[str, Any]]] = {"train": [], "val": [], "test": []}
    n_clusters = len(clusters)
    n_tr = max(1, int(round(n_clusters * 0.70)))
    n_va = max(1, int(round(n_clusters * 0.15))) if n_clusters >= 7 else 0
    for i, cl in enumerate(clusters):
        name = "train" if i < n_tr else ("val" if i < n_tr + n_va else "test")
        out[name].extend(cl)
    if not out["test"] and n_clusters > 2:
        out["test"].extend(out["train"][:1])
        out["train"] = out["train"][1:]
    for k in out:
        rng.shuffle(out[k])

    if coverage is not None:
        tr_keys = {template_key(r) for r in out["train"]}
        te_keys = {template_key(r) for r in out["test"]}
        va_keys = {template_key(r) for r in out["val"]}
        coverage.update({
            "group_split": group_split,
            "n_clusters": n_clusters,
            "train_test_template_overlap": len(tr_keys & te_keys),
            "val_test_template_overlap": len(va_keys & te_keys),
            "n_templates": len(by),
            "splits": {k: len(v) for k, v in out.items()},
        })
    return out


def label_coverage(splits, seqs, vocab: Vocab) -> Dict[str, Any]:
    """门禁所需的覆盖率诊断（纯标准库，可在训练前算出）。"""
    def stats(name):
        dec = [i for s in seqs[name] for i in s if i in vocab.decision_ids]
        by_point = defaultdict(int)
        for i in dec:
            by_point[DECISION_RE.fullmatch(vocab.text_of(i)).group(1)] += 1  # type: ignore[union-attr]
        vals = {vocab.text_of(i).replace("<V:", "").replace(">", "")
                for s in seqs[name] for i in s if i in vocab.validation_ids}
        return {"n_decision_tokens": len(dec), "points": dict(by_point),
                "validation_codes": sorted(vals)}
    tr, te = stats("train"), stats("test")
    points_all = sorted(set(tr["points"]) | set(te["points"]))
    return {
        "train": tr, "test": te,
        "points_with_any_label": points_all,
        "points_with_test_labels": sorted(te["points"]),
        "n_points_with_test_labels": len(te["points"]),
        "n_test_decision_rows": sum(1 for s in seqs["test"]
                                    if any(i in vocab.decision_ids for i in s)),
        "validation_codes_seen": sorted(set(tr["validation_codes"]) | set(te["validation_codes"])),
        "has_err_validation": any(c != "PASS" for c in
                                  set(tr["validation_codes"]) | set(te["validation_codes"])),
    }


def make_batches(seqs: Sequence[Sequence[int]], vocab: Vocab, seq_len: int,
                 batch_size: int, control_weight: float, rng: random.Random,
                 limit: Optional[int] = None) -> List[Dict[str, Any]]:
    order = list(range(len(seqs)))
    rng.shuffle(order)
    batches: List[Dict[str, Any]] = []
    truncated = 0
    for start in range(0, len(order), batch_size):
        if limit is not None and len(batches) >= limit:
            break
        rows_x: List[List[int]] = []
        rows_y: List[List[int]] = []
        rows_w: List[List[float]] = []
        for idx in order[start:start + batch_size]:
            ids = list(seqs[idx])[:seq_len + 1]
            if len(list(seqs[idx])) > seq_len + 1:
                truncated += 1
            x, y = ids[:-1], ids[1:]
            w = [0.0 if t == vocab.pad_id else
                 (control_weight if vocab.kind_of(t) in ("structure", "decision", "validation")
                  else 1.0) for t in y]
            pad = seq_len - len(x)
            rows_x.append(x + [vocab.pad_id] * pad)
            rows_y.append(y + [vocab.pad_id] * pad)
            rows_w.append(w + [0.0] * pad)
        batches.append({"x": rows_x, "y": rows_y, "w": rows_w})
    return batches


def dataset_stats(seqs: Sequence[Sequence[int]], vocab: Vocab) -> Dict[str, Any]:
    total = sum(len(s) for s in seqs)
    dec = sum(1 for s in seqs for i in s if i in vocab.decision_ids)
    val = sum(1 for s in seqs for i in s if i in vocab.validation_ids)
    st = sum(1 for s in seqs for i in s if i in vocab.structure_ids)
    # 只数「传入的这批序列」里的 UNK id。v1 读的是 Vocab.unk_count 全局累积
    # 计数器，会把其它 split 与 shuffle 组重复构建的 UNK 也算进来，
    # 结果随调用次数翻倍（本机 77 / OpenI 154），不可复现。
    unk = sum(1 for s in seqs for i in s if i == vocab.unk_id)
    return {
        "samples": len(seqs), "tokens": total,
        "decision_tokens": dec, "validation_tokens": val, "structure_tokens": st,
        "decision_density": round(dec / max(total, 1), 6),
        "decision_density_ok": dec / max(total, 1) <= DENSITY_MAX,
        "mean_len": round(total / max(len(seqs), 1), 1),
        "max_len": max((len(s) for s in seqs), default=0),
        "unk_tokens": unk,
        "unk_ratio": round(unk / max(total, 1), 6),
        "unk_ratio_scope": "训练序列 token 口径（与词表报告的字符级 UNK 率不同）",
        "validation_codes_seen": sorted({vocab.text_of(i).replace("<V:", "").replace(">", "")
                                         for s in seqs for i in s if i in vocab.validation_ids}),
    }


