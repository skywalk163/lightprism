    rows = load_samples(payload)
    cfg = {
        "schema": SCHEMA, "preset": args.preset, "epochs": args.epochs,
        "batch_size": args.batch_size, "seq_len": args.seq_len,
        "lr": args.lr, "weight_decay": args.weight_decay, "warmup_ratio": args.warmup_ratio,
        "min_lr_ratio": args.min_lr_ratio, "grad_clip": args.grad_clip,
        "control_weight": args.control_weight, "decision_policy": args.decision_policy,
        "group_split": args.group_split, "decision_position": args.decision_position,
        "a_group_rival": args.a_group_rival, "min_decisive_gap": args.min_decisive_gap,
        "no_report_to_repo": args.no_report_to_repo,
        "seed": args.seed, "log_every": args.log_every, "amp": args.amp,
        "eval_gen_samples": args.eval_gen_samples, "max_new_tokens": args.max_new_tokens,
        "probe_epochs": args.probe_epochs, "baseline_epochs": args.baseline_epochs,
        "shuffle_control": not args.no_shuffle_control, "b_group": not args.skip_b_group,
        "steps_limit": args.steps_limit or None, "smoke": args.smoke,
        "epoch_limit": None,
    }
    split_diag: Dict[str, Any] = {}
    splits = stratified_split(rows, args.seed, group_split=args.group_split,
                              coverage=split_diag)
    cfg["split_diagnostics"] = split_diag

    if args.self_check:
        return self_check(payload, vocab, rows, splits, cfg)

    import torch
    device = torch.device(args.device or ("cuda" if torch.cuda.is_available() else "cpu"))
    autocast, scaler, dtype = amp_helpers(device, torch, args.amp)
    env = env_report(device)
    env["amp"] = dtype
    print("== 环境 ==", json.dumps(env, ensure_ascii=False))

    # 输出目录：--out-dir > c2net output_path > cwd/lightprism_out
    c2net_upload = None
    out_dir = Path(args.out_dir) if args.out_dir else Path.cwd() / "lightprism_out"
    if args.c2net:
        try:
            from c2net.context import prepare, upload_output  # type: ignore
            ctx = prepare()
            out_dir = Path(getattr(ctx, "output_path", None) or out_dir)
            c2net_upload = upload_output
            print(f"[openi] c2net output_path = {out_dir}")
        except Exception as exc:  # c2net 缺失/未授权都不该让训练失败
            print(f"[openi] c2net 不可用，改用本地目录：{exc}")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "checkpoints").mkdir(exist_ok=True)
    (out_dir / "train_log.jsonl").unlink(missing_ok=True)   # 不混上次运行的日志

    # ---- 序列与 batch ----
    def seqs_for(policy, shuffle_seed=None):
        rng = random.Random(shuffle_seed) if shuffle_seed is not None else None
        out = {}
        for name in ("train", "val", "test"):
            out[name] = [build_ids(r, vocab, policy, rng,
                                   decision_position=args.decision_position,
                                   position_rng=random.Random(args.seed + 5000 + i))[0]
                         for i, r in enumerate(splits[name])]
        return out

    c_seqs = seqs_for(args.decision_policy)
    b_seqs = {k: [strip_controls(s, vocab) for s in v] for k, v in c_seqs.items()}
    shuf_seqs = seqs_for(args.decision_policy, shuffle_seed=args.seed + 991) \
        if cfg["shuffle_control"] else None

    # v3 门禁诊断：纯标准库，训练前就能算出这轮有没有资格判定
    coverage = label_coverage(splits, c_seqs, vocab)
    coverage["split_diagnostics"] = split_diag
    print("== v3 覆盖诊断 ==", json.dumps(coverage, ensure_ascii=False))

    st = dataset_stats(c_seqs["train"], vocab)
    st["over_seq_len_samples"] = sum(1 for s in c_seqs["train"] if len(s) > args.seq_len + 1)
    st.update({"vocab_size": vocab.vocab_size, "ctrl_start": vocab.ctrl_start,
               "ctrl_end": vocab.ctrl_end, "points": vocab.points,
               "samples": len(rows),
               "splits": {k: len(v) for k, v in splits.items()},
               "payload": payload["meta"]})
    cfg.update({"data_stats": st, "env": env})
    (out_dir / "config.json").write_text(
        json.dumps(cfg, ensure_ascii=False, indent=2), encoding="utf-8")
    print("== 数据 ==", json.dumps(st, ensure_ascii=False))

    def batches_for(seqs, seed):
        all_ep = []
        for ep in range(args.epochs):
            all_ep.append(make_batches(
                seqs["train"], vocab, args.seq_len, args.batch_size,
                args.control_weight, random.Random(seed + ep), cfg["steps_limit"]))
        vb = make_batches(seqs["val"], vocab, args.seq_len, args.batch_size,
                          args.control_weight, random.Random(seed + 7777))
        return all_ep, vb

    kind_table = torch.tensor(vocab.kind_table, dtype=torch.long, device=device)
    torch.manual_seed(args.seed)
    if device.type == "cuda":
        torch.cuda.manual_seed_all(args.seed)
    random.seed(args.seed)

    # 启动自检：一个真实的前向+反向，AMP API 有问题时立刻报清楚
    probe_batch = make_batches(c_seqs["train"][:2], vocab, min(32, args.seq_len), 2,
                               args.control_weight, random.Random(0), limit=1)[0]
    tmp = PrismModel(vocab.vocab_size, PRESETS[args.preset], seed=args.seed).net.to(device)
    with autocast():
        x, y, w = to_device(probe_batch, torch, device, vocab)
        _, l, _ = tmp(x, y, w)
    l.backward()
    del tmp, x, y, w, l
    if device.type == "cuda":
        torch.cuda.empty_cache()
    print(f"[self-test] 前向/反向 OK（dtype={dtype}）")

    metrics: Dict[str, Any] = {"dtype": dtype, "coverage": coverage}

    def run_group(tag: str, seqs, seed: int):
        model = PrismModel(vocab.vocab_size, PRESETS[args.preset], seed=seed)
        model.net.to(device)
        ep_batches, val_batches = batches_for(seqs, seed)
        summary = train_group(model, ep_batches, val_batches, vocab, device, cfg,
                              autocast, scaler, torch, tag, out_dir, kind_table)
        best = out_dir / "checkpoints" / f"{tag}_best.pt"
        if best.exists():
            try:
                blob = torch.load(best, map_location=device, weights_only=False)
            except TypeError:  # torch < 2.0 不认 weights_only
                blob = torch.load(best, map_location=device)
            model.net.load_state_dict(blob["model"])
        return model, summary

    def eval_generation(model: PrismModel, tag: str, expect_validation: bool) -> Dict[str, Any]:
        subset = splits["test"][:args.eval_gen_samples]
        free, cons, samples_out = [], [], []
        for row in subset:
            f = generate(model, vocab, row, device, torch, autocast,
                         args.max_new_tokens, False, expect_validation)
            c = generate(model, vocab, row, device, torch, autocast,
                         args.max_new_tokens, True, expect_validation)
            free.append(f)
            cons.append(c)
            samples_out.append({"tag": tag, "category": row["_category"],
                                "task": row["task"], "free_code": f["code_text"][:400],
                                "answer": f["answer_text"][:400],
                                "free_structure_ok": f["structure_ok"],
                                "free_problems": f["structure_problems"],
                                "constrained_structure_ok": c["structure_ok"],
                                "json_exact": f["json_exact"]})
        counted = [r for r in free if not r["truncated"]]
        jt = [r for r in free if r["is_json_task"]]
        n_valid = sum(1 for r in jt if r["json_valid"])
        n_exact = sum(1 for r in jt if r["json_exact"])
        tps = sum(r["tokens_per_s"] for r in free) / max(len(free), 1)
        dec_density = (sum(r["n_decision"] for r in free) /
                       max(sum(r["n_tokens"] for r in free), 1))
        # v3：判据 ③ 用**全分母**。截断生成必然没吐出 </CODE>/<V:...>，
        # check_structure 必判非法，是一次失败输出，不许从分母里剔除。
        n_all = len(free)
        n_struct_ok_all = sum(1 for r in free if r["structure_ok"] and not r["truncated"])
        return {
            "free": {
                "structure_rate": round(sum(1 for r in counted if r["structure_ok"]) /
                                        len(counted), 4) if counted else None,
                "structure_rate_all": round(n_struct_ok_all / n_all, 4) if n_all else None,
                "n_all": n_all,
                "n_counted": len(counted), "n_truncated": len(free) - len(counted),
                "n_struct_ok_all": n_struct_ok_all,
                "tokens_per_s": round(tps, 1),
            },
            "constrained": {
                "structure_rate": round(sum(1 for r in cons if r["structure_ok"] and not r["truncated"]) /
                                        max(sum(1 for r in cons if not r["truncated"]), 1), 4),
                "note": "外部状态机强制，不计入判据 ③，仅对照",
            },
            "json": {"n": len(jt), "valid": n_valid, "exact": n_exact,
                     "valid_rate": round(n_valid / max(len(jt), 1), 4),
                     "exact_rate": round(n_exact / max(len(jt), 1), 4),
                     "non_json_tasks_unknown": len(free) - len(jt)},
            "decision_density": round(dec_density, 6),
            "samples": samples_out,
        }

    print("\n===== C 组：统一序列（本方案） =====")
    c_model, c_train = run_group("C", c_seqs, args.seed)
    metrics["C"] = {"train": {k: v for k, v in c_train.items() if k != "history"},
                    "probe": train_probe(c_model, vocab, splits, c_seqs, device, torch,
                                         autocast, args.probe_epochs, args.seed),
                    "gen": eval_generation(c_model, "C", True)}
    metrics["params"] = c_model.net.n_params()
    print("C 探针:", json.dumps(metrics["C"]["probe"], ensure_ascii=False))

    # v3 P2：阶段一几何检查点（§7）+ 梯度范数摘要（§8.6）
    metrics["embedding_geometry"] = embedding_geometry(
        c_model, vocab, c_seqs["train"], torch)
    metrics["grad_norm_summary"] = grad_norm_summary(c_train.get("history", []))
    print("几何检查点:", json.dumps(metrics["embedding_geometry"], ensure_ascii=False))

    print("\n===== A 组：外挂轻量决策分类器 =====")
    metrics["A"] = train_decision_baseline(vocab, splits, c_seqs, device, torch,
                                           args.baseline_epochs, args.seed)
    print("A:", json.dumps(metrics["A"], ensure_ascii=False))

    if args.a_group_rival:
        print("\n===== A' 组：冻结主干 + 同 pos-1 特征 + MLP（对等对照） =====")
        metrics["A_rival"] = train_probe_rival(
            c_model, vocab, splits, c_seqs, device, torch, autocast,
            args.probe_epochs, args.seed)
        print("A':", json.dumps(metrics["A_rival"], ensure_ascii=False))

    if cfg["b_group"]:
        print("\n===== B 组：去掉决策/验证 token 的纯生成 =====")
        b_model, b_train = run_group("B", b_seqs, args.seed + 101)
        b_gen = eval_generation(b_model, "B", False)
        metrics["B"] = {"train": {k: v for k, v in b_train.items() if k != "history"},
                        "gen": b_gen}
        c_tps, b_tps = metrics["C"]["gen"]["free"]["tokens_per_s"], b_gen["free"]["tokens_per_s"]
        metrics["C"]["gen"]["speed_drop_vs_B"] = round(max(0.0, (b_tps - c_tps) / max(b_tps, 1e-6)), 4)
    else:
        metrics["C"]["gen"]["speed_drop_vs_B"] = None

    if cfg["shuffle_control"]:
        print("\n===== 负对照：决策标签同点内打乱 =====")
        s_model, s_train = run_group("shuffle", shuf_seqs, args.seed + 202)
        metrics["shuffle"] = {"train": {k: v for k, v in s_train.items() if k != "history"},
                              "probe": train_probe(s_model, vocab, splits, shuf_seqs, device,
                                                   torch, autocast, args.probe_epochs, args.seed),
                              "gen": {"free": {}, "constrained": {}, "json": {}}}

    verdict = judge(metrics, cfg)
    metrics["verdict"] = verdict
    (out_dir / "metrics.json").write_text(
        json.dumps(metrics, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    with (out_dir / "generated_samples.jsonl").open("w", encoding="utf-8") as fh:
        for tag in ("C", "B", "shuffle"):
            if tag in metrics and metrics[tag].get("gen", {}).get("samples"):
                for s in metrics[tag]["gen"]["samples"]:
                    fh.write(json.dumps(s, ensure_ascii=False) + "\n")
    report_md = render_report(metrics, cfg, env, st, verdict)
    (out_dir / "report.md").write_text(report_md, encoding="utf-8")

    # v3 P3：docs/探针实验设计.md §8 产出物——把报告与原始指标落进 reports/
    if not args.no_report_to_repo:
        try:
            repo_reports = Path(__file__).resolve().parent / "reports"
            repo_reports.mkdir(parents=True, exist_ok=True)
            stamp = time.strftime("%Y-%m-%d")
            (repo_reports / f"探针实验_{stamp}.md").write_text(report_md, encoding="utf-8")
            (repo_reports / f"探针实验_{stamp}.json").write_text(
                json.dumps(metrics, ensure_ascii=False, indent=2, default=str),
                encoding="utf-8")
            print(f"[report] §8 产出物已写入 {repo_reports}/探针实验_{stamp}.{{md,json}}")
        except OSError as exc:
            print(f"[report] 仓库 reports/ 不可写，跳过 §8 产出物：{exc}")

    print("\n===== 结论 =====")
    print(json.dumps(verdict, ensure_ascii=False, indent=2))
    print(f"\n全部产物：{out_dir.resolve()}")
    if args.c2net_upload and c2net_upload:
        c2net_upload()
        print("[openi] upload_output() 已调用")
    return 0 if verdict["verdict"] != "invalid" else 2


