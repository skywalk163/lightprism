def _load_payload(args: argparse.Namespace) -> Dict[str, Any]:
    if args.data_dir:
        d = Path(args.data_dir)
        vocab = json.loads((d / "vocab_4096.json").read_text(encoding="utf-8"))
        payload = {
            "vocab": {k: vocab[k] for k in ("schema_version", "kind", "size", "tokens",
                                           "kinds", "control_layout", "counts") if k in vocab},
            "json_tasks": (d / "json_tasks.jsonl").read_text(encoding="utf-8"),
            "code_tasks": (d / "code_tasks.jsonl").read_text(encoding="utf-8"),
            "meta": {"source": "external-data-dir", "dir": str(d.resolve())},
        }
    else:
        raw = zlib.decompress(base64.b64decode("".join(_PAYLOAD_B64.split())))
        payload = json.loads(raw.decode("utf-8"))
    payload["meta"] = dict(payload.get("meta") or {})
    for k in ("json_tasks", "code_tasks"):
        payload["meta"][k + "_sha256"] = hashlib.sha256(
            payload[k].encode("utf-8")).hexdigest()
    payload["meta"]["vocab_sha256"] = hashlib.sha256(
        json.dumps(payload["vocab"], ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()
    return payload


def env_report(device) -> Dict[str, Any]:
    import torch
    out: Dict[str, Any] = {
        "python": sys.version.split()[0],
        "torch": torch.__version__,
        "cuda_available": torch.cuda.is_available(),
        "device": str(device),
    }
    if torch.cuda.is_available():
        p = torch.cuda.get_device_properties(device)
        out.update({
            "gpu": p.name,
            "compute_capability": f"{p.major}.{p.minor}",
            "gpu_memory_gb": round(p.total_memory / (1024 ** 3), 2),
            "torch_is_bf16_supported": bool(getattr(torch.cuda, "is_bf16_supported", lambda: False)()),
            "native_bf16_tensorcore": p.major >= 8,
            "cudnn": torch.backends.cudnn.version(),
        })
    return out


def amp_helpers(device, torch, amp_mode: str):
    """返回 (autocast_ctx_factory, scaler, dtype_name)。

    V100/Volta (SM70) 没有 bf16 Tensor Core。实测 torch 2.10+cu128 在
    Tesla V100S 上 ``is_bf16_supported()`` 返回 **True**（bf16 可软件模拟），
    但既拿不到硬件加速、尾数精度还低于 fp16（7 位 vs 10 位）。
    因此按 compute capability 判断：SM < 8.0 一律 fp16 + GradScaler，
    只有 Ampere+ 且 torch 也报告支持时才用 bf16。
    """
    if device.type != "cuda":
        return (lambda: contextlib.nullcontext()), None, "fp32"
    major, minor = torch.cuda.get_device_capability(device)
    native_bf16 = major >= 8
    torch_says = bool(getattr(torch.cuda, "is_bf16_supported", lambda: False)())
    if amp_mode == "off":
        return (lambda: contextlib.nullcontext()), None, "fp32"
    if amp_mode == "auto":
        dtype = torch.bfloat16 if (native_bf16 and torch_says) else torch.float16
        print(f"[amp] SM{major}.{minor} native_bf16_tensorcore={native_bf16}, "
              f"torch.is_bf16_supported={torch_says} -> {dtype} "
              + ("（V100/Volta 强制 fp16，不要被 torch 的 True 骗了）" if not native_bf16 else ""))
    elif amp_mode == "bf16":
        dtype = torch.bfloat16
    elif amp_mode == "fp16":
        dtype = torch.float16
    else:
        raise ValueError(f"未知 --amp {amp_mode}")

    def ctx():
        try:  # torch >= 2.4
            return torch.amp.autocast(device_type="cuda", dtype=dtype)
        except (AttributeError, TypeError):  # torch 1.13 ~ 2.3
            return torch.cuda.amp.autocast(dtype=dtype)

    scaler = None
    if dtype == torch.float16:
        try:
            scaler = torch.amp.GradScaler("cuda", enabled=True)
        except (AttributeError, TypeError):
            scaler = torch.cuda.amp.GradScaler(enabled=True)
    return ctx, scaler, str(dtype).replace("torch.", "")


